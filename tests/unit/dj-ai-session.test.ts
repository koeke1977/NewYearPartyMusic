import { describe, expect, it, vi } from "vitest";
import { getOrCreateDjAiSessionId } from "../../apps/web/modules/dj-ai-session.js";

function storage(initial = "") {
  const values = new Map(initial ? [["partyqueue_dj_ai_session", initial]] : []);
  return {
    getItem: vi.fn(key => values.get(key) || null),
    setItem: vi.fn((key, value) => values.set(key, value)),
  };
}

describe("DJ AI browser session", () => {
  it("reuses a valid persisted session ID", () => {
    const id = "11111111-1111-4111-8111-111111111111";
    const store = storage(id);
    expect(getOrCreateDjAiSessionId(store, vi.fn())).toBe(id);
    expect(store.setItem).not.toHaveBeenCalled();
  });

  it("creates and persists a new UUID when no valid session exists", () => {
    const id = "22222222-2222-4222-8222-222222222222";
    const store = storage();
    expect(getOrCreateDjAiSessionId(store, () => id)).toBe(id);
    expect(store.setItem).toHaveBeenCalledWith("partyqueue_dj_ai_session", id);
  });

  it("rejects an invalid ID generated by the browser provider", () => {
    expect(() => getOrCreateDjAiSessionId(storage(), () => "not-a-uuid")).toThrow(/sessie-ID/);
  });
});
